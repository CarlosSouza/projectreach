int halopad_mac_key(uint16_t keycode, uint32_t *vk, uint32_t *side_vk, uint32_t *scan, int *extended)
{
    if (keycode >= 128 || !mac[keycode].vk) return 0;
    *vk = mac[keycode].vk; *side_vk = mac[keycode].side; *scan = mac[keycode].scan; *extended = mac[keycode].ext;
    return 1;
}
